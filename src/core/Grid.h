#pragma once

// ---------------------------------------------------------------------------
//  画布网格
//
//  网格间距同时决定三件事：画布上画的小格、元件/导线的吸附步长、
//  以及网表里「两个引脚算不算连在一起」的判定。所以它必须是一处可配的值，
//  不能像以前那样在各处写死 10.0。
//
//  选择存在 QSettings（grid/size），启动时 load() 读回来。
// ---------------------------------------------------------------------------

namespace csm {
namespace Grid {

/// 当前网格间距（逻辑像素），默认 10
double size();
/// 设置并写盘（会被夹到 [1, 100]）
void setSize(double value);
/// 启动时从 QSettings 读回来
void load();

/// 界面上提供的几档，给设置窗口用
double constexpr kOptions[] = {1.0, 2.0, 5.0, 10.0};

} // namespace Grid
} // namespace csm
